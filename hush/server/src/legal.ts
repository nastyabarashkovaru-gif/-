/**
 * Публичная оферта и политика конфиденциальности.
 * ЧЕРНОВИКИ: перед запуском оплаты тексты должен проверить юрист.
 * Реквизиты подставляются из переменных LEGAL_NAME, LEGAL_INN, LEGAL_OGRNIP, LEGAL_EMAIL.
 */
import { Router } from 'express';
import { config } from './config';
import { PLANS, RETURNING_MULTIPLIER, REVEAL_PRICE } from './plans';

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);
const field = (value: string, placeholder: string) =>
  value ? esc(value) : `<mark>[${placeholder}]</mark>`;

function details() {
  const l = config.legal;
  return {
    name: field(l.name, 'ФИО индивидуального предпринимателя'),
    inn: field(l.inn, 'ИНН'),
    ogrnip: field(l.ogrnip, 'ОГРНИП'),
    email: l.email ? `<a href="mailto:${esc(l.email)}">${esc(l.email)}</a>` : '<mark>[email для обращений]</mark>',
    bank: l.account
      ? `<br>Р/с ${esc(l.account)}<br>Банк: ${esc(l.bank)}<br>БИК ${esc(l.bik)}<br>К/с ${esc(l.corrAccount)}`
      : '',
  };
}

const rub = (n: number) => `${n.toLocaleString('ru-RU').replace(/\s/g, ' ')} ₽`;

function page(title: string, body: string) {
  return `<!doctype html><html lang="ru"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title>${title} — hush.</title>
<style>
body{margin:0;background:#000;color:#e9e7ee;font:16px/1.55 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Arial,sans-serif}
main{max-width:720px;margin:0 auto;padding:28px 20px 60px}
h1{font-size:26px;line-height:1.2;margin:0 0 6px;color:#fff}h2{font-size:18px;margin:28px 0 8px;color:#fff}
p,li{color:#c9c6d1}a{color:#b987ff}mark{background:#3b2a12;color:#ffcf7a;padding:0 4px;border-radius:4px}
.muted{color:#8e8b97;font-size:14px}.logo{font-weight:700;font-size:24px;margin-bottom:24px}.logo b{color:#a855f7}
</style></head><body><main><div class="logo">hush<b>.</b></div>${body}</main></body></html>`;
}

const UPDATED = '10 октября 2026 г.';

function offer() {
  const d = details();
  const plans = Object.values(PLANS)
    .map((p) => `<li>${esc(p.title.replace('hush. Premium — ', ''))} — ${rub(p.amount)}, списание раз в ${p.months === 1 ? 'месяц' : p.months === 3 ? '3 месяца' : '12 месяцев'};</li>`)
    .join('');
  return page(
    'Публичная оферта',
    `<h1>Публичная оферта</h1><p class="muted">о предоставлении доступа к платным функциям сервиса hush. · редакция от ${UPDATED}</p>

<h2>1. Общие положения</h2>
<p>1.1. Индивидуальный предприниматель ${d.name} (ИНН ${d.inn}, ОГРНИП ${d.ogrnip}), далее — «Исполнитель», предлагает любому дееспособному лицу (далее — «Пользователь») заключить договор на условиях настоящей оферты.</p>
<p>1.2. Сервис hush. — мини-приложение Telegram @Hush_miniapp_bot, позволяющее создавать анкеты и получать анонимные ответы других пользователей (далее — «Сервис»).</p>
<p>1.3. Акцептом оферты является оплата подписки. С момента оплаты договор считается заключённым.</p>

<h2>2. Предмет</h2>
<p>2.1. Исполнитель предоставляет Пользователю доступ к платным функциям Сервиса (подписка «Premium»): просмотр всех полученных ответов, создание новых анкет без ограничений, добавление своих вопросов в новые анкеты, а также просмотр Telegram-профиля авторов ответов, которые явно разрешили это при отправке ответа: на годовом тарифе — без ограничений, на тарифах «1 месяц» и «3 месяца» — за отдельную разовую плату за каждого автора.</p>
<p>2.2. Профиль автора ответа никогда не раскрывается без его согласия. Если автор остался анонимным, его профиль не будет показан ни на одном тарифе.</p>

<h2>3. Тарифы и оплата</h2>
<ul>${plans}</ul>
<p>Разовое раскрытие одного автора ответа на тарифах «1 месяц» и «3 месяца» — ${rub(REVEAL_PRICE)}. Это разовый платёж без автопродления.</p>
<p>Повторное оформление подписки после её отмены Пользователем производится по тарифам, увеличенным в ${RETURNING_MULTIPLIER} раза. Итоговая цена указывается на экране выбора тарифа до оплаты.</p>
<p>3.1. Оплата производится банковской картой через платёжный сервис CloudPayments. Данные карты обрабатывает платёжный сервис, Исполнитель их не получает и не хранит.</p>
<p>3.2. Подписка продлевается автоматически: по окончании оплаченного периода с карты списывается стоимость того же тарифа за следующий период, пока Пользователь не отключит автопродление.</p>

<h2>4. Отмена подписки</h2>
<p>4.1. Отменить подписку можно в любой момент в настройках профиля: «Настройки» → «Управлять подпиской» → «Отменить подписку». Доступ к Premium сохраняется до конца оплаченного периода, новые списания не производятся.</p>
<p>4.2. Также отменить подписку можно, написав на ${d.email}.</p>
<p>4.3. При отмене подписки Исполнитель может предложить скидку 50% на один следующий платёж по текущему тарифу. Последующие платежи списываются по обычной цене тарифа.</p>

<h2>5. Возврат средств</h2>
<p>5.1. Пользователь вправе отказаться от договора и потребовать возврата денежных средств за неиспользованный период, направив заявление на ${d.email}. Возврат производится на карту, с которой была произведена оплата, в течение 10 рабочих дней.</p>

<h2>6. Правила использования</h2>
<p>6.1. Запрещено использовать Сервис для оскорблений, угроз, травли, распространения персональных данных третьих лиц и иной противоправной информации. Исполнитель вправе ограничить доступ Пользователю, нарушающему эти правила.</p>
<p>6.2. Ответы в анкетах пишут другие пользователи. Исполнитель не отвечает за их содержание, но удаляет противоправные материалы по обращению на ${d.email}.</p>
<p>6.3. Сервис скрывает ответы, пока анкету не заполнят минимум 5 человек, чтобы затруднить определение автора, однако не может гарантировать абсолютную анонимность: автора иногда можно угадать по содержанию ответа.</p>

<h2>7. Персональные данные</h2>
<p>7.1. Обработка персональных данных осуществляется в соответствии с <a href="/legal/privacy">Политикой конфиденциальности</a>.</p>

<h2>8. Реквизиты Исполнителя</h2>
<p>Индивидуальный предприниматель ${d.name}<br>ИНН ${d.inn}<br>ОГРНИП ${d.ogrnip}${d.bank}<br>Email: ${d.email}</p>`,
  );
}

function privacy() {
  const d = details();
  return page(
    'Политика конфиденциальности',
    `<h1>Политика конфиденциальности</h1><p class="muted">редакция от ${UPDATED}</p>

<h2>1. Оператор</h2>
<p>Оператор персональных данных — ИП ${d.name} (ИНН ${d.inn}). Контакт для обращений: ${d.email}.</p>

<h2>2. Какие данные мы обрабатываем</h2>
<ul>
<li>данные Telegram-аккаунта, которые передаёт Telegram при открытии мини-приложения: идентификатор, имя, фамилия, имя пользователя (username), фото профиля;</li>
<li>созданные анкеты и выбранные вопросы;</li>
<li>тексты ответов на анкеты других пользователей;</li>
<li>согласие или отказ на раскрытие своего профиля автору анкеты — с датой и версией текста согласия;</li>
<li>сведения об оплатах: тариф, сумма, дата, идентификаторы платежа и подписки. Данные банковских карт обрабатывает CloudPayments, мы их не получаем.</li>
</ul>

<h2>3. Зачем</h2>
<ul>
<li>предоставление функций Сервиса: создание анкет, сбор и показ ответов;</li>
<li>раскрытие профиля автора ответа — только если автор явно на это согласился;</li>
<li>уведомления от бота о новых ответах — только если пользователь разрешил боту писать ему;</li>
<li>оформление и учёт подписки, исполнение требований закона о бухгалтерском учёте и онлайн-кассах;</li>
<li>защита от злоупотреблений: ограничение частоты запросов, запрет повторных ответов.</li>
</ul>

<h2>4. Анонимность ответов</h2>
<p>Автор анкеты видит тексты ответов, но не видит, кто их написал. Профиль автора ответа показывается владельцу анкеты только при одновременном выполнении двух условий: автор ответа явно разрешил это при отправке и у владельца анкеты есть годовая подписка. Ответы открываются, когда анкету заполнят минимум 5 человек.</p>

<h2>5. Кому передаются данные</h2>
<ul>
<li>Telegram — для работы мини-приложения и отправки уведомлений;</li>
<li>CloudPayments — для приёма оплаты и чеков;</li>
<li>хостинг-провайдеру, на серверах которого работает Сервис.</li>
</ul>
<p>Мы не продаём данные и не передаём их для рекламы.</p>

<h2>6. Сроки хранения</h2>
<p>Данные хранятся, пока пользуетесь Сервисом. По запросу на ${d.email} мы удалим ваши анкеты, ответы и данные аккаунта в течение 30 дней, кроме сведений об оплатах, которые обязаны хранить по закону.</p>

<h2>7. Ваши права</h2>
<p>Вы вправе запросить сведения о своих данных, их уточнение или удаление, а также отозвать согласие на обработку, написав на ${d.email}.</p>`,
  );
}

export const legal = Router();
legal.get('/offer', (_req, res) => {
  res.type('html').send(offer());
});
legal.get('/privacy', (_req, res) => {
  res.type('html').send(privacy());
});
